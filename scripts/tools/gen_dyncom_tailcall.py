#!/usr/bin/env python3
"""Generates a tail-call version of the dyncom interpreter (arm_dyncom_interpreter_tc.inc).

The original InterpreterMainLoop is one huge function whose handlers are labels reached through
`goto *InstLabel[idx]`. Clang lowers every computed goto to a single shared indirect branch,
and the handlers' shared locals (inst_base, ptr, num_instrs) end up spilled. Here every handler
becomes its own function taking those locals as arguments, and each one ends in its own
[[clang::musttail]] call to the next handler: one indirect branch per handler, state in
registers. The handler bodies are copied verbatim; only `goto DISPATCH` / `goto END` and the
FETCH_INST / GOTO_NEXT_INST macros change meaning.

usage: gen_dyncom_tailcall.py <azahar src/core/arm> <output .inc>
"""
import re, sys

arm, out = sys.argv[1], sys.argv[2]
interp = open(f"{arm}/dyncom/arm_dyncom_interpreter.cpp").read().split("\n")
vfp = open(f"{arm}/skyeye_common/vfp/vfpinstr.cpp").read().split("\n")

LABEL = re.compile(r"^([A-Z][A-Z0-9_]*)\s*:\s*(?:/\*.*\*/\s*)?(\{)?\s*$")


def strip_code(line):
    """Line without // comments, string and char literals (for brace counting)."""
    s = re.sub(r'"(\\.|[^"\\])*"', '""', line)
    s = re.sub(r"'(\\.|[^'\\])*'", "''", s)
    return s.split("//")[0]


def parse(lines, start, stop):
    """[(labels, body_lines)] for label blocks in lines[start:stop]."""
    groups, pending, i = [], [], start
    while i < stop:
        m = LABEL.match(lines[i])
        if not m:
            i += 1
            continue
        pending.append(m.group(1))
        if not m.group(2):
            if i + 1 < stop and lines[i + 1].strip() == "{":  # brace on the next line
                i += 1
            else:  # alias label: the block follows
                i += 1
                continue
        depth, body, j = 1, [], i + 1
        while j < stop:
            code = strip_code(lines[j])
            depth += code.count("{") - code.count("}")
            if depth == 0:
                break
            body.append(lines[j])
            j += 1
        assert depth == 0, f"unbalanced block at {pending}"
        groups.append((pending, body))
        pending, i = [], j + 1
    assert not pending, pending
    return groups


d = next(n for n, l in enumerate(interp) if l.startswith("DISPATCH: {"))
v = next(n for n, l in enumerate(interp) if l.startswith("#define VFP_INTERPRETER_IMPL"))
e = next(n for n, l in enumerate(interp) if l.startswith("END: {"))
groups = parse(interp, d, v)
vfp_groups = []
k = 0
while k < len(vfp):
    if vfp[k].startswith("#ifdef VFP_INTERPRETER_IMPL"):
        depth, end = 0, k
        for n in range(k, len(vfp)):
            if vfp[n].lstrip().startswith("#if"):
                depth += 1
            elif vfp[n].lstrip().startswith("#endif"):
                depth -= 1
                if depth == 0:
                    end = n
                    break
        vfp_groups += parse(vfp, k + 1, end)
        k = end
    k += 1
tail = parse(interp, e, len(interp) - 1)  # END, INIT_INST_LENGTH (the function's final } excluded)
all_groups = groups + vfp_groups + tail

# Label order of the InstLabel table.
t0 = next(n for n, l in enumerate(interp) if "InstLabel[] = {" in l)
order = []
for l in interp[t0:]:
    order += re.findall(r"&&([A-Z0-9_]+)", l)
    if "};" in l:
        break
fn_of = {}
for labels, _ in all_groups:
    for lab in labels:
        fn_of[lab] = "TC_" + labels[-1]
missing = [l for l in order if l not in fn_of]
assert not missing, missing

o = []
w = o.append
w("// Generated by scripts/tools/gen_dyncom_tailcall.py from arm_dyncom_interpreter.cpp and")
w("// vfpinstr.cpp. Do not edit; re-run the script after changing either file.")
w("// Included at the end of arm_dyncom_interpreter.cpp (needs the macros defined there).")
w("")
for labels, _ in all_groups:
    w(f"static TC_CC unsigned TC_{labels[-1]}(TC_ARGS);")
w("")
w(f"static constexpr TcHandler tc_table[{len(order)}] = {{")
for lab in order:
    w(f"    {fn_of[lab]},")
w("};")
w("")
w("#ifdef ENABLE_GDBSTUB // breakpoints are not checked on this path")
w("#undef GDB_BP_CHECK")
w("#define GDB_BP_CHECK")
w("#endif")
w("#undef FETCH_INST")
w("#undef GOTO_NEXT_INST")
w("#define TC_GOTO_DISPATCH [[clang::musttail]] return TC_DISPATCH(TC_PASS)")
w("#define TC_GOTO_END [[clang::musttail]] return TC_END(TC_PASS)")
w("#define FETCH_INST                                                                                 \\")
w("    if (inst_base->br != TransExtData::NON_BRANCH) {                                               \\")
w("        TC_GOTO_DISPATCH;                                                                          \\")
w("    }                                                                                              \\")
w("    inst_base = (arm_inst*)&trans_cache_buf[ptr]")
w("#define GOTO_NEXT_INST                                                                             \\")
w("    if (num_instrs >= cpu->NumInstrsToExecute) {                                                   \\")
w("        TC_GOTO_END;                                                                               \\")
w("    }                                                                                              \\")
w("    num_instrs++;                                                                                  \\")
w("    [[clang::musttail]] return tc_table[inst_base->idx](TC_PASS)")
w("")
for labels, body in all_groups:
    name = labels[-1]
    if len(labels) > 1:
        w(f"// {', '.join(labels)}")
    w(f"static TC_CC unsigned TC_{name}(TC_ARGS) {{")
    w("    [[maybe_unused]] unsigned int addr;")
    if name == "DISPATCH":
        w("#ifdef ENABLE_GDBSTUB")
        w("    [[maybe_unused]] GDBStub::BreakpointAddress breakpoint_data{};")
        w("#endif")
    for l in body:
        l = l.replace("goto DISPATCH;", "TC_GOTO_DISPATCH;").replace("goto END;", "TC_GOTO_END;")
        assert "goto " not in strip_code(l), f"{name}: {l}"
        w(l)
    w("}")
    w("")
w("#undef TC_GOTO_DISPATCH")
w("#undef TC_GOTO_END")
open(out, "w").write("\n".join(o) + "\n")
print(f"{len(all_groups)} handlers, table {len(order)}", file=sys.stderr)
